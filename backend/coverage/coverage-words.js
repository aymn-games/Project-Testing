/** كل الأزواج (لفئة معيّنة أو الكل) كمفاتيح ثابتة 'فئة:رقم' عشان ما يتكرر الزوج بنفس الروم. */
function allKeys(cat) {
    var out = [];
    CATEGORIES.forEach(function (c) {
        if (cat && cat !== 'all' && c.id !== cat) return;
        c.pairs.forEach(function (p, i) { out.push(c.id + ':' + i); });
    });
    return out;
}

function byKey(key) {
    var parts = String(key).split(':'), c = CATEGORIES.find(function (x) { return x.id === parts[0]; });
    var p = c && c.pairs[Number(parts[1])];
    return p ? { cat: c.id, catName: c.n, a: p[0], b: p[1] } : null;
}

/**
 * يختار زوج بعيد عن آخر الأزواج المستخدمة بالروم، ويقلب الترتيب عشوائياً
 * (فمرة «مطار» للأغلبية ومرة للخارج عن التغطية).
 * @returns {{cat, catName, word, alt, key}}
 */
function pick(cat, recent, rnd) {
    rnd = rnd || Math.random;
    var keys = allKeys(cat);
    if (!keys.length) keys = allKeys('all');
    var fresh = keys.filter(function (k) { return (recent || []).indexOf(k) < 0; });
    if (!fresh.length) fresh = keys;
    var key = fresh[Math.floor(rnd() * fresh.length)], p = byKey(key), flip = rnd() < 0.5;
    return { cat: p.cat, catName: p.catName, word: flip ? p.b : p.a, alt: flip ? p.a : p.b, key: key };
}

/**
 * توحيد الكتابة العربية للمقارنة: بدون تشكيل وتطويل ومسافات، والهمزات ألف،
 * والتاء المربوطة هاء، والألف المقصورة ياء، وبدون «ال» بالبداية.
 */
function normalize(s) {
    var t = String(s == null ? '' : s).toLowerCase()
        .replace(/[ً-ْٰـ]/g, '')
        .replace(/[أإآٱ]/g, 'ا').replace(/ة/g, 'ه').replace(/ى/g, 'ي').replace(/ؤ/g, 'و').replace(/ئ/g, 'ي')
        .replace(/[^ء-يa-z0-9 ]/g, ' ').replace(/\s+/g, ' ').trim();
    return t.split(' ').map(function (w) { return w.length > 3 && w.indexOf('ال') === 0 ? w.slice(2) : w; }).join('');
}

/** تخمين الكلمة: يطابق بعد التوحيد (مطار = المطار = مطار.) */
function matches(guess, word) {
    var g = normalize(guess), w = normalize(word);
    return !!g && g === w;
}

/** التلميح فيه الكلمة نفسها؟ (ممنوع ذكرها مباشرة) */
function containsWord(hint, word) {
    var h = normalize(hint), w = normalize(word);
    return w.length >= 2 && h.indexOf(w) >= 0;
}


    var TENS = ['', 'عشرة', 'عشرون', 'ثلاثون', 'أربعون', 'خمسون', 'ستون', 'سبعون', 'ثمانون', 'تسعون'];
    var HUNDREDS = ['', 'مئة', 'مئتان', 'ثلاثمئة', 'أربعمئة', 'خمسمئة', 'ستمئة', 'سبعمئة', 'ثمانمئة', 'تسعمئة'];
    var THOUSANDS = ['', 'ألف', 'ألفان', 'ثلاثة آلاف', 'أربعة آلاف', 'خمسة آلاف', 'ستة آلاف', 'سبعة آلاف', 'ثمانية آلاف', 'تسعة آلاف'];
    function below100(n) {
        if (n < 10) return UNITS[n];
        if (n === 10) return TENS[1];
        if (n === 11) return 'أحد عشر';
        if (n === 12) return 'اثنا عشر';
        if (n < 20) return UNITS[n - 10] + ' عشر';
        var u = n % 10, t = Math.floor(n / 10);
        return u ? UNITS[u] + ' و' + TENS[t] : TENS[t];
    }
    function numberWords(n) {
        var parts = [];
        var th = Math.floor(n / 1000), h = Math.floor(n % 1000 / 100), r = n % 100;
        if (th) parts.push(THOUSANDS[th]);
        if (h) parts.push(HUNDREDS[h]);
        if (r) parts.push(below100(r));
        return parts.join(' و');
    }
    var NUMBER = [];
    for (var n = 11; n <= 9999; n++) NUMBER.push([numberWords(n), n]);

    var FA_QUESTIONS = {
        image: IMAGE,
        reverse: REVERSE,
        number: NUMBER,
        capital: COUNTRIES.filter(function (c) { return c[2]; }).map(function (c) { return [c[1], c[2], c[4] || []]; }),
        proverb: PROVERB,
        scramble: SCRAMBLE,
        flag: COUNTRIES.map(function (c) { return [c[0], c[1], c[3] || []]; }),
        complete: COMPLETE,
        odd: ODD,
        plural: PLURAL,
        opposite: OPPOSITE,
        currency: CURRENCY,
        sentence: SENTENCE
    };

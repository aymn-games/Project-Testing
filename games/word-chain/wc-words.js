    /** تطبيع للمقارنة: يوحّد الحروف المتشابهة ويحذف التشكيل والرموز والمسافات الزائدة. */
    function normalize(text) {
        return String(text == null ? '' : text)
            .replace(/[ً-ٰٟـ]/g, '')
            .replace(/[أإآٱ]/g, 'ا')
            .replace(/ة/g, 'ه')
            .replace(/[ىی]/g, 'ي')
            .replace(/ؤ/g, 'و')
            .replace(/ئ/g, 'ي')
            .replace(/ک/g, 'ك')
            .replace(/[^ء-ي\s]/g, ' ')
            .replace(/\s+/g, ' ')
            .trim();
    }

    function key(text) {
        return normalize(text).replace(/ /g, '');
    }

    /** الحروف اللي تُحسب بداية للكلمة: الحرف الأول، ولو تبدأ بـ«ال» فالحرف اللي بعدها كمان ("اليونان" = ا أو ي). */
    function firstLetters(text) {
        var k = key(text), out = [];
        if (k) out.push(k.charAt(0));
        if (/^ال/.test(k) && k.length > 3 && out.indexOf(k.charAt(2)) < 0) out.push(k.charAt(2));
        return out;
    }

    function firstLetter(text) {
        return firstLetters(text)[0] || '';
    }

    /** الحروف اللي تُحسب نهاية للكلمة — الهمزة الأخيرة تُتخطّى، والتاء المربوطة تُحسب "ت" أو "ه" (الاثنين مقبولين). */
    function lastLetters(text) {
        var raw = String(text == null ? '' : text).replace(/[ً-ٰٟـ\s]+$/, '');
        if (/ة$/.test(raw)) return ['ت', 'ه'];
        var k = key(raw).replace(/ء+$/, '');
        var l = k.charAt(k.length - 1);
        return l ? [l] : [];
    }

    function lastLetter(text) {
        return lastLetters(text)[0] || '';
    }

    function intersects(a, b) {
        for (var i = 0; i < a.length; i++) if (b.indexOf(a[i]) >= 0) return true;
        return false;
    }

    /** صيغ إضافية تلقائية: الكلمة بدون «ال» ("يونان" = "اليونان")، والكلمة المفردة مع «ال» ("الكويت" = "كويت"). */
    function autoForms(form) {
        var f = form.trim();
        if (/^ال/.test(f) && key(f).length > 4) return [f.slice(2)];
        if (f.indexOf(' ') < 0) return ['ال' + f];
        return [];
    }

    var index = {};
    CATEGORIES.forEach(function (cat) {
        var byKey = {};
        var entries = [];
        RAW[cat.id].split('\n').forEach(function (line) {
            line = line.trim();
            if (!line) return;
            var forms = line.split('|').map(function (f) { return f.trim(); }).filter(Boolean);
            var entry = { id: cat.id + ':' + key(forms[0]), display: forms[0], forms: forms };
            entries.push(entry);
            forms.forEach(function (form) {
                var k = key(form);
                if (!byKey[k]) byKey[k] = { entry: entry, form: form };
            });
        });
        // الصيغ التلقائية بعد كل الصيغ الأصلية، حتى ما تغطي على كلمة حقيقية بنفس الشكل
        entries.forEach(function (entry) {
            entry.forms.forEach(function (form) {
                autoForms(form).forEach(function (alt) {
                    var k = key(alt);
                    if (k && !byKey[k]) byKey[k] = { entry: entry, form: alt };
                });
            });
        });
        cat.entries = entries;
        index[cat.id] = byKey;
    });

    /**
     * يبحث عن تعليق داخل فئة. يرجع null إذا لم يكن كلمة مقبولة.
     * النتيجة: { entryId, display, form, firsts, lasts } — الحروف من الصيغة المكتوبة.
     */
    function lookup(categoryId, text) {
        var byKey = index[categoryId];
        if (!byKey) return null;
        var hit = byKey[key(text)];
        if (!hit) return null;
        return {
            entryId: hit.entry.id,
            display: hit.entry.display,
            form: hit.form,
            firsts: firstLetters(hit.form),
            lasts: lastLetters(hit.form)
        };
    }

    /** الكلمات (غير المستخدمة) اللي تبدأ بأحد الحروف المطلوبة — لاختيار البداية، والتلميح، وكشف الحرف "المقفول". */
    function entriesStartingWith(categoryId, letters, usedIds) {
        var cat = CATEGORIES.filter(function (c) { return c.id === categoryId; })[0];
        if (!cat) return [];
        var want = Array.isArray(letters) ? letters : [letters];
        var used = usedIds || {};
        return cat.entries.filter(function (e) {
            if (used[e.id]) return false;
            return e.forms.some(function (f) { return intersects(firstLetters(f), want); });
        });
    }

    /** صيغة من الكلمة تبدأ بأحد الحروف المطلوبة (للتلميح). */
    function formStartingWith(entry, letters) {
        var want = Array.isArray(letters) ? letters : [letters];
        return entry.forms.filter(function (f) { return intersects(firstLetters(f), want); })[0] || entry.display;
    }

    window.AGPWordChainWords = {
        categories: CATEGORIES,
        normalize: normalize,
        firstLetter: firstLetter,
        firstLetters: firstLetters,
        lastLetter: lastLetter,
        lastLetters: lastLetters,
        intersects: intersects,
        lookup: lookup,
        entriesStartingWith: entriesStartingWith,
        formStartingWith: formStartingWith
    };
